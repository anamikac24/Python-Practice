# GFG

x = int(input()) # 5
y = int(input()) # 2

p = x+y # 7
q = x-y # 3
r = x*y # 10
s = x/y # 2.5 --> Performs standard floating-point division (returning a decimal).
t = x//y # 2 --> Performs floor/integer division (discarding the fractional part).
u = x%y  # 1 --> Calculates the modulo (remainder).
print(p, q, r, s, t, u) # Outputs all results separated by spaces.
